type Opts = { storage: string; ram: string; sim: string };

function phone(
  name: string,
  price: number,
  stock: 0 | 3,
  { storage, ram, sim }: Opts,
  blurb: string,
  specs: Record<string, string>,
): DeviceRow {
  return { name, price, stock, options: { Stockage: storage, RAM: ram, SIM: sim }, blurb, specs };
}

